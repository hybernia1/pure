import { mkdir, readFile, writeFile, cp, rm, readdir } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { utilities } from './utilities.mjs';
import { writeMinified } from './minify.mjs';

const names = ['tokens', 'base', 'components', 'states', 'flash', 'editor', 'forms', 'controls', 'modal', 'upload', 'resize', 'activity', 'progress', 'search', 'tag-picker', 'drag-drop', 'media-library', 'data', 'tabs', 'navigation'];
const parts = await Promise.all(names.map((name) => readFile(`src/css/${name}.css`, 'utf8')));
const output = resolve('dist');
if (dirname(output) !== resolve('.') || output === resolve('.')) throw new Error('Invalid build output path');
await rm(output, { recursive: true, force: true });
await mkdir('dist/pure/css', { recursive: true });
await mkdir('dist/pure/js', { recursive: true });
for (let i = 0; i < names.length; i++) await writeFile(`dist/pure/css/${names[i]}.css`, parts[i]);
const generated = utilities();
await writeFile('dist/pure/css/utilities.css', generated);
await writeFile('dist/pure/pure.css', [...parts, generated].join('\n'));
await cp('src/js', 'dist/pure/js', { recursive: true });
await cp('src/icons.svg', 'dist/pure/icons.svg');
const moduleFiles = await Promise.all(['js', 'css'].map(async directory => (await readdir(`dist/pure/${directory}`)).map(name => `${directory}/${name}`)));
await writeMinified(['pure.css', 'icons.svg', ...moduleFiles.flat()]);
console.log('Pure built -> dist/pure/ and dist/pure.min/');
