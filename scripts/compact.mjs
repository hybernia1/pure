import { build, transform } from 'esbuild';
import { readFile, writeFile, cp, mkdir } from 'node:fs/promises';

const registry = await readFile('src/js/lazy.js', 'utf8');
const components = [...registry.matchAll(/^\s*(?:'([^']+)'|([\w-]+)):\s*\[/gm)]
  .map(match => match[1] || match[2]);
if (!components.includes('editor') || !components.includes('modal')) throw Error('Cannot read component registry.');

function closure(start, imports) {
  const found = new Set();
  const visit = path => {
    if (found.has(path)) return;
    found.add(path);
    for (const dependency of imports(path)) visit(dependency);
  };
  visit(start);
  return [...found];
}

export async function manifestFile(components, variant) {
  const code = '// Generated by npm run build. Keep with its matching distribution.\n'
    + `export const preloadManifest = ${JSON.stringify({ version: 1, components }, null, 2)};\n`;
  return variant === 'pure.min' ? (await transform(code, { minify: true, format: 'esm' })).code : code;
}

export const compactOptions = variant => ({
  entryPoints: {
    editor: 'src/js/editor.js',
    ui: 'scripts/ui-entry.mjs',
    lazy: 'src/js/lazy.js',
    preload: 'src/js/preload.js'
  },
  bundle: true,
  splitting: true,
  format: 'esm',
  target: 'es2022',
  keepNames: true,
  minify: variant === 'pure.min',
  sourcemap: false,
  legalComments: 'eof',
  chunkNames: '[name]-[hash]',
  outdir: `dist/${variant}/compact/js`,
  metafile: true
});

export function compactManifest(result) {
  const outputs = result.metafile.outputs;
  const plans = {};
  for (const name of components) {
    const entry = Object.keys(outputs).find(path => outputs[path].entryPoint === `src/js/${name}.js`);
    if (!entry) throw Error(`Missing compact entry: ${name}`);
    plans[name] = closure(entry, path => (outputs[path]?.imports || [])
      .filter(dependency => dependency.kind === 'import-statement' && !dependency.external)
      .map(dependency => dependency.path))
      .map(path => 'js/' + path.split('/').at(-1));
  }
  return plans;
}

export async function regularManifest() {
  const analysis = await build({
    entryPoints: components.map(name => `src/js/${name}.js`),
    bundle: true, splitting: true, format: 'esm', write: false,
    metafile: true, outdir: 'analysis', logLevel: 'silent'
  });
  const regular = {};
  for (const name of components) {
    regular[name] = closure(`src/js/${name}.js`, path => (analysis.metafile.inputs[path]?.imports || [])
      .filter(dependency => dependency.kind === 'import-statement' && !dependency.external)
      .map(dependency => dependency.path))
      .map(path => 'js/' + path.split('/').at(-1));
  }
  return regular;
}

export async function buildProfiles() {
  const regular = await regularManifest();
  for (const variant of ['pure', 'pure.min']) {
    const root = `dist/${variant}`;
    const compact = `${root}/compact`;
    await mkdir(`${compact}/js`, { recursive: true });
    for (const file of ['css', 'pure.css', 'icons.svg']) {
      await cp(`${root}/${file}`, `${compact}/${file}`, { recursive: true });
    }
    await writeFile(`${root}/js/preload-manifest.js`, await manifestFile(regular, variant));
    const result = await build(compactOptions(variant));
    await writeFile(`${compact}/js/preload-manifest.js`, await manifestFile(compactManifest(result), variant));
  }
}
